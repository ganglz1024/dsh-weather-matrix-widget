/**
 * Assemble the browser artifact (client.js) from parts/.
 *
 * The Web Client module loader consumes one file per package: a global
 * `window.__ModuleLoader__.load({ id, factory(require) { ... } })` call whose
 * factory returns the Plugin object. ESM `import` is not available inside that
 * factory, so the parts are plain function/const declarations concatenated into
 * the factory body (React comes from the loader's module table).
 *
 * Run:  node build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ID = 'dsh-weather-matrix-widget'
const PARTS = [
  'parts/05-font.js',
  'parts/00-data.js',
  'parts/10-matrix.js',
  'parts/20-icons.js',
  'parts/30-view.js',
  'parts/90-register.js',
]

const body = PARTS.map((file) => {
  const source = readFileSync(join(here, file), 'utf8').replace(/\r\n/g, '\n')
  return `// ===== ${file} =====\n${source.trimEnd()}`
}).join('\n\n')

const indented = body
  .split('\n')
  .map((line) => (line.length > 0 ? `    ${line}` : ''))
  .join('\n')

const artifact = `/* Generated by build.mjs from parts/ — do not edit this file directly. */
window.__ModuleLoader__.load({
  id: '${ID}',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
${indented}

    return { inject: ['slots'], apply: wxApply };
  },
});
`

writeFileSync(join(here, 'client.js'), artifact, 'utf8')
console.log(`client.js written (${Buffer.byteLength(artifact, 'utf8')} bytes, ${artifact.split('\n').length} lines)`)